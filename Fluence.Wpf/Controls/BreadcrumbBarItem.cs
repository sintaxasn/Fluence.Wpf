using System;
using System.Diagnostics.CodeAnalysis;
using System.Windows;
using System.Windows.Automation;
using System.Windows.Automation.Peers;
using System.Windows.Automation.Provider;
using System.Windows.Input;
using System.Windows.Media;
using System.Windows.Threading;

namespace Fluence.Wpf.Controls
{
    /// <summary>
    /// The visual crumb generated by <see cref="BreadcrumbBar"/> for each item: a subtle
    /// button-like content host followed by a chevron separator that the default template
    /// hides on the last (current) crumb. Crumbs are keyboard focusable and activate through
    /// a mouse left-button release, Enter, or Space, raising <see cref="Click"/>.
    /// </summary>
    public class BreadcrumbBarItem : System.Windows.Controls.ContentControl
    {
        private sealed class BreadcrumbBarItemAutomationPeer(BreadcrumbBarItem owner) : FrameworkElementAutomationPeer(owner), IInvokeProvider
        {
            protected override string GetClassNameCore()
            {
                return nameof(BreadcrumbBarItem);
            }

            protected override AutomationControlType GetAutomationControlTypeCore()
            {
                return AutomationControlType.Button;
            }

            protected override string GetNameCore()
            {
                return owner.GetAccessibleText();
            }

            public override object? GetPattern(PatternInterface patternInterface)
            {
                return patternInterface is PatternInterface.Invoke ? this : base.GetPattern(patternInterface);
            }

            public void Invoke()
            {
                if (!IsEnabled())
                {
                    throw new ElementNotEnabledException();
                }

                // Match WPF ButtonAutomationPeer: a navigation handler may open a dialog,
                // so UIA Invoke must return before the click is dispatched.
                _ = owner.Dispatcher.BeginInvoke(DispatcherPriority.Input, new Action(() =>
                {
                    if (owner.IsEnabled)
                    {
                        owner.RaiseEvent(new RoutedEventArgs(ClickEvent, owner));
                    }
                }));
            }
        }

        /// <summary>
        /// Initializes static members of the BreadcrumbBarItem class and overrides the default
        /// style metadata so the control picks up its themed template from Generic.xaml.
        /// </summary>
        static BreadcrumbBarItem()
        {
            DefaultStyleKeyProperty.OverrideMetadata(
                typeof(BreadcrumbBarItem),
                new FrameworkPropertyMetadata(typeof(BreadcrumbBarItem)));
        }

        private static readonly DependencyPropertyKey IsLastItemPropertyKey =
            DependencyProperty.RegisterReadOnly(
                nameof(IsLastItem),
                typeof(bool),
                typeof(BreadcrumbBarItem),
                new FrameworkPropertyMetadata(defaultValue: false));

        /// <summary>
        /// Identifies the <see cref="IsLastItem"/> dependency property.
        /// </summary>
        public static readonly DependencyProperty IsLastItemProperty =
            IsLastItemPropertyKey.DependencyProperty;

        /// <summary>
        /// Gets whether this crumb is the last (current) item of its owning
        /// <see cref="BreadcrumbBar"/>. The default template hides the chevron separator and
        /// switches to primary SemiBold typography while this is <see langword="true"/>.
        /// </summary>
        public bool IsLastItem
        {
            get => (bool)GetValue(IsLastItemProperty);
            internal set => SetValue(IsLastItemPropertyKey, value);
        }

        private static readonly DependencyPropertyKey IsPressedPropertyKey =
            DependencyProperty.RegisterReadOnly(
                nameof(IsPressed),
                typeof(bool),
                typeof(BreadcrumbBarItem),
                new FrameworkPropertyMetadata(defaultValue: false));

        /// <summary>
        /// Identifies the <see cref="IsPressed"/> dependency property.
        /// </summary>
        public static readonly DependencyProperty IsPressedProperty =
            IsPressedPropertyKey.DependencyProperty;

        /// <summary>
        /// Gets whether the crumb is currently pressed.
        /// </summary>
        public bool IsPressed
        {
            get => (bool)GetValue(IsPressedProperty);
            private set => SetValue(IsPressedPropertyKey, value);
        }

        /// <summary>
        /// Identifies the <see cref="Click"/> routed event.
        /// </summary>
        public static readonly RoutedEvent ClickEvent =
            EventManager.RegisterRoutedEvent(
                nameof(Click),
                RoutingStrategy.Bubble,
                typeof(RoutedEventHandler),
                typeof(BreadcrumbBarItem));

        /// <summary>
        /// Occurs when the crumb is activated by a mouse left-button release that began with
        /// a press inside the crumb bounds, or by the Enter or Space key while focused. The
        /// owning <see cref="BreadcrumbBar"/> aggregates this into
        /// <see cref="BreadcrumbBar.ItemClicked"/>.
        /// </summary>
        [SuppressMessage("Design", "S3908", Justification = "RoutedEventHandler is required by WPF's routed event infrastructure.")]
        public event RoutedEventHandler Click
        {
            add => AddHandler(ClickEvent, value);
            remove => RemoveHandler(ClickEvent, value);
        }

        /// <inheritdoc />
        protected override AutomationPeer OnCreateAutomationPeer()
        {
            return new BreadcrumbBarItemAutomationPeer(this);
        }

        internal string GetAccessibleText()
        {
            string explicitName = AutomationProperties.GetName(this);
            if (!string.IsNullOrWhiteSpace(explicitName))
            {
                return explicitName;
            }

            UIElement? label = AutomationProperties.GetLabeledBy(this);
            if (label is not null &&
                GetPeerName(UIElementAutomationPeer.CreatePeerForElement(label)) is string labelName &&
                !string.IsNullOrWhiteSpace(labelName))
            {
                return labelName;
            }

            string namedContent = FindExplicitName(this);
            if (!string.IsNullOrWhiteSpace(namedContent))
            {
                return namedContent;
            }

            string renderedText = FindRenderedText(this);
            return !string.IsNullOrWhiteSpace(renderedText)
                ? renderedText
                : Content?.ToString() ?? string.Empty;
        }

        private static string? GetPeerName(AutomationPeer? peer)
        {
            // WPF can return no peer when the label does not implement one.
            return peer?.GetName();
        }

        private static string FindExplicitName(DependencyObject element)
        {
            string name = AutomationProperties.GetName(element);
            if (!string.IsNullOrWhiteSpace(name))
            {
                return name;
            }

            for (int index = 0; index < VisualTreeHelper.GetChildrenCount(element); index++)
            {
                string childName = FindExplicitName(VisualTreeHelper.GetChild(element, index));
                if (!string.IsNullOrWhiteSpace(childName))
                {
                    return childName;
                }
            }

            return string.Empty;
        }

        private static string FindRenderedText(DependencyObject element)
        {
            if (element is System.Windows.Controls.TextBlock textBlock &&
                !string.IsNullOrWhiteSpace(textBlock.Text))
            {
                return textBlock.Text;
            }

            for (int index = 0; index < VisualTreeHelper.GetChildrenCount(element); index++)
            {
                string childText = FindRenderedText(VisualTreeHelper.GetChild(element, index));
                if (!string.IsNullOrWhiteSpace(childText))
                {
                    return childText;
                }
            }

            return string.Empty;
        }

        /// <inheritdoc />
        protected override void OnKeyDown(KeyEventArgs e)
        {
            base.OnKeyDown(e);
            if (IsEnabled && e.Key is Key.Enter or Key.Space)
            {
                IsPressed = true;
                e.Handled = true;
            }
        }

        /// <inheritdoc />
        protected override void OnKeyUp(KeyEventArgs e)
        {
            base.OnKeyUp(e);
            if (IsEnabled && e.Key is Key.Enter or Key.Space)
            {
                bool wasPressed = IsPressed;
                IsPressed = false;
                if (wasPressed)
                {
                    RaiseEvent(new RoutedEventArgs(ClickEvent, this));
                }
                e.Handled = true;
            }
        }

        /// <inheritdoc />
        protected override void OnMouseLeftButtonDown(MouseButtonEventArgs e)
        {
            base.OnMouseLeftButtonDown(e);
            if (IsEnabled)
            {
                IsPressed = true;
                _ = CaptureMouse();
            }
        }

        /// <inheritdoc />
        protected override void OnMouseLeftButtonUp(MouseButtonEventArgs e)
        {
            base.OnMouseLeftButtonUp(e);
            bool wasPressed = IsPressed;
            if (wasPressed)
            {
                IsPressed = false;
                ReleaseMouseCapture();
            }
            if (wasPressed && IsEnabled)
            {
                RaiseEvent(new RoutedEventArgs(ClickEvent, this));
            }
        }

        /// <inheritdoc />
        protected override void OnLostMouseCapture(MouseEventArgs e)
        {
            base.OnLostMouseCapture(e);
            IsPressed = false;
        }

        /// <inheritdoc />
        protected override void OnMouseLeave(MouseEventArgs e)
        {
            base.OnMouseLeave(e);
            if (IsPressed)
            {
                IsPressed = false;
                ReleaseMouseCapture();
            }
        }
    }
}
